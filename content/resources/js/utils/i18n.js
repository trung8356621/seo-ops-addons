function normalizeLocale(value) {
    const locale = String(value || '').trim().toLowerCase();
    if (locale.startsWith('vi')) return 'vi';
    return 'en';
}

export function getSeoLocale() {
    const fromWindow = typeof window !== 'undefined' ? window.__SEO_I18N_LOCALE__ : '';
    const fromHtml = typeof document !== 'undefined'
        ? document.documentElement?.getAttribute('lang')
        : '';
    return normalizeLocale(fromWindow || fromHtml || 'en');
}

export function t(key, params = {}) {
    const locale = getSeoLocale();
    const fallback = dictionaries.en[key] ?? key;
    const raw = (dictionaries[locale] && dictionaries[locale][key]) || fallback;
    return String(raw).replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? ''));
}
